"""Draws the app icon and writes it into app/icons.py as base64.

Committed as data rather than as .png files on purpose: the NAS deployment story
is "copy the code folder, restart", and that stays true only if the app is one
kind of thing. A handful of binary assets that must also be copied, in the right
place, is exactly the sort of small extra step that goes wrong once and then is
hard to see.

The one exception is `windows/PhotoManager.ico`, written beside the launcher.
Windows wants a real file for a shortcut's icon and for the tray, and it wants
each size drawn for that size: a 256px picture shrunk to 16px by Explorer is a
blue smudge. So every size an .ico is asked for is drawn here, at that size.

Run this only when the icon changes:  python tools/make_icon.py
"""

import base64
import io
import os

from PIL import Image, ImageDraw

OUT = os.path.join(os.path.dirname(__file__), "..", "app", "icons.py")
ICO = os.path.join(os.path.dirname(__file__), "..", "windows", "PhotoManager.ico")

# What Windows asks an .ico for: 16 to 32 in the tray and in lists (more at
# higher display scaling), 48 for desktop icons, 256 for Explorer's large views.
ICO_SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)

BLUE = (44, 107, 237)
DEEP = (28, 74, 173)
WHITE = (255, 255, 255)
SKY = (223, 234, 255)


def draw(size: int) -> Image.Image:
    """A photo standing in front of another photo. Legible down to 16px.

    Drawn at 8x and shrunk, which is the cheap way to get smooth curves out of
    Pillow's non-antialiased shape drawing.
    """
    s = size * 8
    im = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)

    # the rounded-square ground
    d.rounded_rectangle([0, 0, s - 1, s - 1], radius=int(s * 0.22), fill=BLUE)

    # the photo behind, peeking out at the top left
    back = [s * 0.20, s * 0.20, s * 0.72, s * 0.66]
    d.rounded_rectangle(back, radius=int(s * 0.05), fill=SKY)

    # the photo in front
    x0, y0, x1, y1 = s * 0.30, s * 0.33, s * 0.82, s * 0.80
    d.rounded_rectangle([x0, y0, x1, y1], radius=int(s * 0.05), fill=WHITE)

    # its picture: a sun and two hills, the universal "this is a photo"
    d.ellipse([x0 + s * 0.06, y0 + s * 0.06,
               x0 + s * 0.155, y0 + s * 0.155], fill=BLUE)
    d.polygon([(x0 + s * 0.03, y1 - s * 0.04),
               (x0 + s * 0.21, y0 + s * 0.19),
               (x0 + s * 0.34, y1 - s * 0.04)], fill=DEEP)
    d.polygon([(x0 + s * 0.20, y1 - s * 0.04),
               (x0 + s * 0.34, y0 + s * 0.24),
               (x0 + s * 0.50, y1 - s * 0.04)], fill=BLUE)

    return im.resize((size, size), Image.LANCZOS)


def encoded(size: int) -> str:
    buf = io.BytesIO()
    draw(size).save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def wrap(name: str, data: str) -> str:
    lines = [data[i:i + 76] for i in range(0, len(data), 76)]
    body = "\n".join(f'    "{line}"' for line in lines)
    return f"{name} = base64.b64decode(\n{body}\n)\n"


def write_ico(path: str) -> None:
    """Every size drawn at that size, then packed into one .ico."""
    biggest, *rest = [draw(n) for n in sorted(ICO_SIZES, reverse=True)]
    biggest.save(path, format="ICO", sizes=[(n, n) for n in ICO_SIZES],
                 append_images=rest)


def main() -> None:
    parts = [
        '"""The app icon, as bytes. Generated by tools/make_icon.py - do not edit.\n\n'
        'Kept in code so that deploying stays "copy the folder, restart" with no\n'
        'binary assets to place separately.\n"""\n\n'
        "import base64\n\n",
    ]
    for name, size in (("ICON_32", 32), ("ICON_192", 192), ("ICON_512", 512)):
        parts.append(wrap(name, encoded(size)))
        parts.append("\n")
    with open(os.path.abspath(OUT), "w", encoding="utf-8") as fh:
        fh.write("".join(parts))
    print(f"wrote {os.path.abspath(OUT)}")
    for size in (32, 192, 512):
        print(f"  {size}px  {len(encoded(size)) * 3 // 4:,} bytes")
    write_ico(os.path.abspath(ICO))
    print(f"wrote {os.path.abspath(ICO)}  "
          f"({os.path.getsize(os.path.abspath(ICO)):,} bytes, "
          f"{', '.join(str(n) for n in ICO_SIZES)} px)")


if __name__ == "__main__":
    main()
